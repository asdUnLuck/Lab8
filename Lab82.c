#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>
#include <math.h>

double x, dx, y;

int main(void) {
    setlocale(0, "");
    // 1) Вывод функции в качестве приглашения
    printf("Табулирование функции: y = 1.8 * x^2 - sin(10 * x)\n");
    printf("Интервал: [0.2; 2.2]\n");

    // 2) Ввод шага табуляции
    printf("Введите шаг табуляции (например, 0,2 (использовать запятую!!!!)): ");
    scanf("%lf", &dx);

    // 3) Оформление в виде таблицы
    printf("\n_________________________\n");
    printf("|    x    |    f(x)     |\n");
    printf("-------------------------\n");

    // Цикл с произвольным шагом. Добавляем 1e-9, чтобы избежать ошибок округления float
    for (x = 0.2; x <= 2.2 + 1e-9; x += dx) {
        y = 1.8 * x * x - sin(10 * x);
        printf("|  %4.2f   |  %8.4f   |\n", x, y);
    }

    printf("-------------------------\n");

    return 0;
}